def pct(x, d=2):
    return "n/a" if x is None else "%.*f%%" % (d, 100.0 * x)


def f(x, d=3):
    return "n/a" if x is None else "%.*f" % (d, x)


def ci(pair, d=2, percent=True):
    if pair is None:
        return "n/a"
    a, b = pair
    if percent:
        return "[%.*f, %.*f]" % (d, 100 * a, d, 100 * b)
    return "[%.*f, %.*f]" % (d, a, d, b)


def rate_row(name, blk):
    return "| %s | %d / %d | %s | %s | %s |" % (
        name, blk["k"], blk["n"], pct(blk["rate"]), ci(blk["wilson"]),
        ci(blk["seed_boot"]))


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out.extend(rows)
    return out


